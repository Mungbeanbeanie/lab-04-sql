CREATE TABLE USERS (
    USER_ID INT PRIMARY KEY,
    FOLLOWERS INT,
    USERNAME VARCHAR(15),
    BIO TEXT,
    ACCOUNT_CREATED DATETIME
);
CREATE TABLE POSTS (
    POST_ID INT PRIMARY KEY,
    USER_ID INT,
    FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    LIKES INT,
    TITLE VARCHAR(30),
    CAPTION TEXT,
    POSTED DATETIME
);

